/**
 * 会话摘要提示词（规范见 02-backend「会话摘要」）：
 * 对将被截断的旧轮对话生成一次性压缩摘要，按 compaction 原则侧重
 * 用户偏好与画像变化、已投递进度、未决事项/进行中任务、关键决策；丢弃冗余工具输出。
 */

export function buildSessionSummarySystemPrompt(): string {
  return `你是一名求职助手会话归档员。请阅读一段对话记录，为后续轮次的助手生成一份中文压缩摘要，使其在看不到旧轮原文的情况下也能延续对话。
只输出 JSON 对象，不要输出其他文字或 markdown 代码块。
输出 JSON 契约字段（字段名必须严格一致）：
- summary：压缩摘要文本（中文），内容侧重——
  1. 用户偏好与画像变化（求职方向、城市、薪资预期、技术栈、经历背景的声明或修正）；
  2. 已投递进度（已导入的岗位/简历、匹配结果、投递状态推进、渠道信息）；
  3. 未决事项与进行中任务（用户等待的回复、进行中的计划步骤、待确认的动作）；
  4. 关键决策与结论（用户已确认/拒绝的事项及其原因）。
- hasPending：是否存在未决事项或进行中任务（有则 true，否则 false）。

要求：
1. 丢弃冗余的工具输出细节（评分明细、逐条匹配矩阵、渠道清单等中间产物），只保留结论与影响后续轮次的事实。
2. 摘要必须忠于原文，严禁补充、编造或美化原文不存在的经历、技能、雇主、证书或成果。
3. 用第三人称叙述用户事实，简洁分条，不重复已知常识。
4. summary 长度控制在 400 字以内；若原文无实质内容（如纯寒暄），summary 输出对后续轮次仍有用的最小事实即可。`;
}

export function buildSessionSummaryUserPrompt(transcript: string): string {
  return `以下是会话历史中即将被截断的对话记录（每条以「角色：」开头）：

${transcript}

请按系统要求生成压缩摘要与未决事项标记。`;
}
